"""Writes doc/DATA_DICTIONARY.md. Run from backend/: .venv/bin/python scripts/make_data_dictionary.py"""
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from app import config, features  # noqa: E402
from app.feature_info import describe_feature  # noqa: E402

OUTPUT = Path(__file__).resolve().parents[2] / "doc" / "DATA_DICTIONARY.md"

def main():
    definitions = pd.read_csv(config.DATA_DIR / "feature_definitions.csv")

    train = features.load_features("train")
    thin = train["thin_file"] == 1
    lines = [
        "# Data dictionary",
        "",
        "Generated by `backend/scripts/make_data_dictionary.py` from the train feature table "
        f"({len(train):,} loans). Re-run the script after changing `features.py`.",
        "",
        "Suffixes: `A` amount · `P` days past due · `D` date · `M` masked category · `L` / `T` other transform.",
        "",
        f"## Model features ({len(features.feature_columns(train))})",
        "",
        "One row per loan (`case_id`). Depth-1/2 tables are aggregated per `case_id` before joining.",
        "",
        "| Feature | Source table | Type | % missing (all / established / thin-file) | Meaning |",
        "|---|---|---|---|---|",
    ]
    for name in features.feature_columns(train):
        table, meaning = describe_feature(name)
        kind = "category" if str(train[name].dtype) == "category" else "number"
        # Categories keep missing values as a "MISSING" level
        is_missing = train[name] == "MISSING" if kind == "category" else train[name].isna()
        missing = [is_missing.mean(), is_missing[~thin].mean(), is_missing[thin].mean()]
        missing_text = " / ".join(f"{m:.0%}" for m in missing)
        lines.append(f"| `{name}` | {table} | {kind} | {missing_text} | {meaning} |")

    lines += [
        "",
        "## Not used as features",
        "",
        "| Column | Why |",
        "|---|---|",
        "| `case_id` | Join key only |",
        "| `date_decision`, `MONTH`, `WEEK_NUM` | Time of application: used to split the data and for the drift correction, "
        "not as model inputs (a model cannot extrapolate time to future weeks) |",
        "| `target` | The label: 1 = defaulted, 0 = repaid |",
        "| `birth_259D` | Replaced by `age_years` |",
        "| `num_group1`, `num_group2` | Row indexes inside depth-1/2 tables |",
        "",
        "## Raw columns (from the dataset's feature_definitions.csv)",
        "",
        "| Table | Depth | Column | Type | % missing | Description |",
        "|---|---|---|---|---|---|",
    ]
    for row in definitions.itertuples():
        lines.append(f"| {row.table} | {row.depth} | `{row.column}` | {row.dtype} | {row.pct_missing}% | {row.description} |")

    OUTPUT.write_text("\n".join(lines) + "\n")
    print(f"Wrote {OUTPUT}")


if __name__ == "__main__":
    main()
